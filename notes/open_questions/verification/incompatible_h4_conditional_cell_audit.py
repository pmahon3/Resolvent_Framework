ZERO = ('zero',)
ONE = ('one',)


def ekey(e):
    """Canonical deterministic string key for an element."""
    if e == ZERO:
        return "0"
    if e == ONE:
        return "1"
    k, x = e
    if k == 'a':
        return "a:" + x
    if k == 'c':
        return "c:" + x
    return "m:" + "+".join(sorted(x))


class Logic:
    """Pasted poset from a block presentation.

    blocks: list of atom lists (each block = maximal Boolean subalgebra).
    ident: element-level identifications {element: canonical_element}, used to
           paste two 4-atom blocks along the nonmaximal subalgebra {0,q,q',1}.
    couplings: list of (atomset1, atomset2) whose charge-sums must agree in
           every two-valued state (the state-side shadow of ident).
    Order = transitive closure of block-internal Boolean orders. Everything
    downstream is checked exhaustively; nothing is assumed from Greechie theory.
    """

    def __init__(self, name, blocks, ident=None, couplings=None):
        self.name = name
        self.blocks = [tuple(b) for b in blocks]
        self.ident = ident or {}
        self.couplings = [(tuple(s1), tuple(s2)) for s1, s2 in (couplings or [])]
        self.atoms = sorted({a for b in blocks for a in b})
        for B, C in combinations(self.blocks, 2):
            assert len(set(B) & set(C)) <= 1, ("blocks share >1 atom", B, C)
        els = {ZERO, ONE}
        self.block_elems = {}
        self.mid_block = {}
        for bi, B in enumerate(self.blocks):
            n = len(B)
            pairs = []
            for k in range(n + 1):
                for S in combinations(B, k):
                    S = frozenset(S)
                    if k == 0:
                        e = ZERO
                    elif k == n:
                        e = ONE
                    elif k == 1:
                        e = ('a', min(S))
                    elif k == n - 1:
                        e = ('c', min(set(B) - S))
                    else:
                        e = ('m', S)
                        self.mid_block.setdefault(S, bi)
                    e = self.ident.get(e, e)
                    pairs.append((S, e))
            self.block_elems[bi] = pairs
            for S, e in pairs:
                els.add(e)
        self.elements = sorted(els, key=ekey)
        self.n = len(self.elements)
        self.idx = {e: i for i, e in enumerate(self.elements)}
        n = self.n
        le = [[False] * n for _ in range(n)]
        for i in range(n):
            le[i][i] = True
        z, o = self.idx[ZERO], self.idx[ONE]
        for i in range(n):
            le[z][i] = True
            le[i][o] = True
        for bi in self.block_elems:
            ps = self.block_elems[bi]
            for S, e in ps:
                for T, f in ps:
                    if S <= T:
                        le[self.idx[e]][self.idx[f]] = True
        changed = True
        while changed:
            changed = False
            for k in range(n):
                lk = le[k]
                for i in range(n):
                    if le[i][k]:
                        li = le[i]
                        for j in range(n):
                            if lk[j] and not li[j]:
                                li[j] = True
                                changed = True
        self.le = le
        for i in range(n):
            for j in range(n):
                if i != j:
                    assert not (le[i][j] and le[j][i]), \
                        ("antisymmetry", ekey(self.elements[i]), ekey(self.elements[j]))

    def comp(self, e):
        if e == ZERO:
            return ONE
        if e == ONE:
            return ZERO
        k, x = e
        if k == 'a':
            return ('c', x)
        if k == 'c':
            return ('a', x)
        bi = self.mid_block[x]
        f = ('m', frozenset(self.blocks[bi]) - x)
        return self.ident.get(f, f)

    def build_tables(self):
        """Exact latticehood filter: unique glb/lub for every pair, else record
        the FIRST failed pair (deterministic: elements sorted by ekey)."""
        n, le = self.n, self.le
        self.meet = [[None] * n for _ in range(n)]
        self.join = [[None] * n for _ in range(n)]
        self.lattice_ok, self.lattice_fail = True, None
        for i in range(n):
            for j in range(i, n):
                lows = [k for k in range(n) if le[k][i] and le[k][j]]
                tops = [k for k in lows if all(le[t][k] for t in lows)]
                if len(tops) != 1:
                    self.lattice_ok = False
                    self.lattice_fail = {"kind": "meet", "x": ekey(self.elements[i]),
                                         "y": ekey(self.elements[j])}
                    return
                self.meet[i][j] = self.meet[j][i] = tops[0]
                ups = [k for k in range(n) if le[i][k] and le[j][k]]
                bots = [k for k in ups if all(le[k][t] for t in ups)]
                if len(bots) != 1:
                    self.lattice_ok = False
                    self.lattice_fail = {"kind": "join", "x": ekey(self.elements[i]),
                                         "y": ekey(self.elements[j])}
                    return
                self.join[i][j] = self.join[j][i] = bots[0]

    def check_ortholattice(self):
        n, le = self.n, self.le
        cidx = [self.idx[self.comp(e)] for e in self.elements]
        self.cidx = cidx
        for i in range(n):
            assert cidx[cidx[i]] == i
            for j in range(n):
                if le[i][j]:
                    assert le[cidx[j]][cidx[i]], ("antitone", i, j)
            assert self.meet[i][cidx[i]] == self.idx[ZERO]
            assert self.join[i][cidx[i]] == self.idx[ONE]
        for i in range(n):
            for j in range(n):
                if le[i][j]:
                    if self.join[i][self.meet[cidx[i]][j]] != j:
                        return False, {"x": ekey(self.elements[i]), "y": ekey(self.elements[j])}
        return True, None

    # Two-valued states = exactly-one-charged-atom-per-block assignments that
    # respect the couplings. (Hand lemma: additivity on a block forces charge
    # sum 1; atom values determine the state; identified elements force the
    # coupling equations. Additivity is nevertheless re-checked exhaustively.)
    def all_states(self):
        blocks = self.blocks
        val = {}
        out = []

        def coupling_ok():
            for s1, s2 in self.couplings:
                if sum(val[a] for a in s1) != sum(val[a] for a in s2):
                    return False
            return True

        def dfs(bi):
            if bi == len(blocks):
                if coupling_ok():
                    out.append(dict(val))
                return
            B = blocks[bi]
            ones = [a for a in B if val.get(a) == 1]
            if len(ones) > 1:
                return
            cands = ones if ones else [a for a in B if val.get(a) is None]
            for c in cands:
                touched = []
                ok = True
                if val.get(c) is None:
                    val[c] = 1
                    touched.append(c)
                for a in B:
                    if a == c:
                        continue
                    if val.get(a) == 1:
                        ok = False
                        break
                    if val.get(a) is None:
                        val[a] = 0
                        touched.append(a)
                if ok:
                    dfs(bi + 1)
                for a in touched:
                    del val[a]

        dfs(0)
        return out

    def sval(self, sol, e):
        if e == ZERO:
            return 0
        if e == ONE:
            return 1
        k, x = e
        if k == 'a':
            return sol[x]
        if k == 'c':
            return 1 - sol[x]
        v = sum(sol[a] for a in x)
        assert v <= 1
        return v

def audit_payload(name, blocks, triples, q_specs, shared_structure=None,
                  ident=None, couplings=None, include_state_table=False,
                  relations_hook=None):
    """Compute the full deterministic audit payload for one design.

    triples: list of activation triples (atom names).
    q_specs: dict label -> ('m', frozenset) designated coordinate events.
    relations_hook(L, states) -> dict of design-specific relation summaries.
    """
    L = Logic(name, blocks, ident=ident, couplings=couplings)
    payload = {
        "design": name,
        "shared_structure": shared_structure,
        "construction": {
            "atoms": L.atoms,
            "blocks": [sorted(b) for b in L.blocks],
            "identifications": sorted([ekey(k), ekey(v)] for k, v in (ident or {}).items()),
            "couplings": [[sorted(s1), sorted(s2)] for s1, s2 in (couplings or [])],
            "designated": {
                "activation_triples": [list(t) for t in triples],
                **{lab: ekey(e) for lab, e in sorted(q_specs.items())},
            },
        },
        "counts": {"atoms": len(L.atoms), "blocks": len(L.blocks), "elements": L.n},
    }
    L.build_tables()
    payload["audit"] = {"lattice_ok": L.lattice_ok,
                        "first_failed_lattice_pair": L.lattice_fail}
    if not L.lattice_ok:
        return payload
    om_ok, om_wit = L.check_ortholattice()
    payload["audit"]["ortholattice_ok"] = True
    payload["audit"]["orthomodular_ok"] = om_ok
    payload["audit"]["orthomodular_witness"] = om_wit
    if not om_ok:
        return payload

    states = L.all_states()
    ns = len(states)
    payload["counts"]["two_valued_states"] = ns
    full = (1 << ns) - 1
    supp = []
    for e in L.elements:
        m = 0
        for si, s in enumerate(states):
            if L.sval(s, e):
                m |= (1 << si)
        supp.append(m)
    add_ok = True
    for i in range(L.n):
        for j in range(L.n):
            if L.le[i][L.cidx[j]]:
                if supp[L.join[i][j]] != (supp[i] | supp[j]) or (supp[i] & supp[j]):
                    add_ok = False
    odet_ok = all(L.le[i][j] == ((supp[i] | supp[j]) == supp[j])
                  for i in range(L.n) for j in range(L.n))
    inj_ok = len(set(supp)) == L.n
    payload["audit"]["state_additivity_ok"] = add_ok
    payload["audit"]["order_determination_ok"] = odet_ok
    payload["audit"]["support_map_injective_ok"] = inj_ok

    def commutes(i, j):
        return L.join[L.meet[i][j]][L.meet[i][L.cidx[j]]] == i
    payload["audit"]["centre"] = sorted(
        ekey(L.elements[i]) for i in range(L.n)
        if all(commutes(i, j) for j in range(L.n)))

    coh = {a: set() for a in L.atoms}
    for B in L.blocks:
        for x, y in combinations(B, 2):
            coh[x].add(y)
            coh[y].add(x)
    cliques = []

    def bk(R, P, X):
        if not P and not X:
            cliques.append(sorted(R))
            return
        for v in sorted(P):
            bk(R | {v}, P & coh[v], X & coh[v])
            P = P - {v}
            X = X | {v}
    bk(set(), set(L.atoms), set())
    payload["audit"]["maximal_blocks"] = sorted(cliques)
    payload["audit"]["maximal_blocks_equal_declared"] = \
        sorted(cliques) == sorted(sorted(b) for b in L.blocks)

    mo3 = {}
    for trip in triples:
        A = [('a', a) for a in trip]
        gen = {L.idx[e] for e in [ZERO, ONE] + A + [L.comp(e) for e in A]}
        while True:
            new = set(gen)
            for i in gen:
                new.add(L.cidx[i])
                for j in gen:
                    new.add(L.meet[i][j])
                    new.add(L.join[i][j])
            if new == gen:
                break
            gen = new
        rel_ok = all(L.meet[L.idx[x]][L.idx[y]] == L.idx[ZERO]
                     and L.join[L.idx[x]][L.idx[y]] == L.idx[ONE]
                     for x, y in combinations(A, 2))
        mo3[",".join(trip)] = {"generated_subOML_size": len(gen),
                               "mo3_relations_ok": rel_ok,
                               "is_H4_horizontal_sum": len(gen) == 8 and rel_ok}
    payload["audit"]["h4_controls"] = mo3

    esc, norep = {}, {}
    for trip in triples:
        cyl = supp[L.idx[('a', trip[0])]] & supp[L.idx[('a', trip[1])]] \
            & supp[L.idx[('a', trip[2])]]
        key = ",".join(trip)
        esc[key] = all(supp[i] & (full & ~cyl)
                       for i in range(L.n) if L.elements[i] != ZERO)
        norep[key] = (cyl != 0) and all(supp[i] != cyl for i in range(L.n))
    payload["audit"]["escape_every_nonzero_event_charged_off_111"] = esc
    payload["audit"]["no_event_represents_111_cylinder"] = norep

    projections = {}
    for trip in triples:
        for qlab in sorted(q_specs):
            if qlab.startswith("q"):
                continue
            qe, re_ = q_specs["q"], q_specs[qlab]
            fibers = {}
            for s in states:
                bits = "".join(str(L.sval(s, ('a', a))) for a in trip) \
                    + str(L.sval(s, qe)) + str(L.sval(s, re_))
                fibers[bits] = fibers.get(bits, 0) + 1
            pk = ",".join(trip) + "|q," + qlab
            projections[pk] = {
                "fiber_counts": {k: fibers[k] for k in sorted(fibers)},
                "contains_11100": fibers.get("11100", 0) > 0,
                "contains_11111": fibers.get("11111", 0) > 0,
                "excludes_11101": fibers.get("11101", 0) == 0,
                "excludes_11110": fibers.get("11110", 0) == 0,
                "off_111_all_four_qr_profiles": all(
                    fibers.get("%d%d%d%d%d" % (x, y, z, u, v), 0) > 0
                    for x in (0, 1) for y in (0, 1) for z in (0, 1)
                    if (x, y, z) != (1, 1, 1) for u in (0, 1) for v in (0, 1)),
            }
    payload["projections"] = projections

    if relations_hook:
        payload["relations"] = relations_hook(L, states)
    if include_state_table:
        payload["state_table"] = {
            "atom_order": L.atoms,
            "rows": sorted("".join(str(s[a]) for a in L.atoms) for s in states),
        }
    return payload


def canonical(payload):
    return json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()


def compute_all():
    with open(os.path.abspath(__file__), "rb") as f:
        vsha = hashlib.sha256(f.read()).hexdigest()
    out = []
    for fname, kw in build_designs():
        p = audit_payload(**kw)
        p["verifier_sha256"] = vsha
        out.append((fname, p))
    return out


def emit():
    for fname, payload in compute_all():
        receipt = {
            "schema": SCHEMA,
            "schema_version": SCHEMA_VERSION,
            "generator": GENERATOR,
            "command": COMMAND,
            "emitted": EMIT_DATE,
            "payload_sha256": hashlib.sha256(canonical(payload)).hexdigest(),
            "payload": payload,
        }
        path = os.path.join(HERE, fname)
        with open(path, "w") as f:
            json.dump(receipt, f, indent=1, sort_keys=True)
            f.write("\n")
        print("wrote", fname, "payload_sha256=%s..." % receipt["payload_sha256"][:16])


def verify():
    ok = True
    for fname, payload in compute_all():
        path = os.path.join(HERE, fname)
        if not os.path.exists(path):
            print("MISSING ", fname)
            ok = False
            continue
        with open(path) as f:
            receipt = json.load(f)
        stored = receipt.get("payload")
        sha_stored = receipt.get("payload_sha256")
        sha_of_stored = hashlib.sha256(canonical(stored)).hexdigest()
        recomputed = json.loads(canonical(payload).decode())
        if sha_of_stored != sha_stored:
            print("CORRUPT ", fname, "(stored payload does not match its hash)")
            ok = False
        elif recomputed != stored:
            diff = [k for k in set(recomputed) | set(stored)
                    if recomputed.get(k) != stored.get(k)]
            print("MISMATCH", fname, "fields:", sorted(diff))
            ok = False
        else:
            print("MATCH   ", fname, "payload_sha256=%s..." % sha_stored[:16])
    print("VERIFY:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "--verify"
    if mode == "--emit":
        emit()
    elif mode == "--verify":
        sys.exit(verify())
    else:
        print(__doc__)
        sys.exit(2)

def cell_blocks(sfx="", acts=("a1", "a2", "a3"), E=("e11", "e10", "e01", "e00"),
                own_E=True):
    """The gate cell: AND-arm (a1,a2 -> w1), two mediator chains (w1,a3 -> t1,t2),
    difference-killers t1-e10, t2-e01, coordinate block E.
    q = e11 v e10, r = e11 v e01; on activation 111 the cascade forces
    e10 = e01 = 0, so the state projection keeps 11100/11111 and drops
    11101/11110 with no event supported inside the cylinder."""
    a1, a2, a3 = acts

    def s(x):
        return x + sfx
    B = [
        [a1, s("u1"), s("p11")], [a2, s("v1"), s("p12")],
        [s("u1"), s("v1"), s("w1")],
        [a3, s("n1"), s("p15")], [s("w1"), s("m1"), s("p14")],
        [s("m1"), s("n1"), s("t1")],
        [a3, s("n2"), s("p25")], [s("w1"), s("m2"), s("p24")],
        [s("m2"), s("n2"), s("t2")],
        [s("t1"), E[1], s("s1")], [s("t2"), E[2], s("s2")],
    ]
    if own_E:
        B.append(list(E))
    return B


E1 = ("e11", "e10", "e01", "e00")
E2 = ("f11", "f10", "f01", "f00")
Q = ('m', frozenset({"e11", "e10"}))
R = ('m', frozenset({"e11", "e01"}))
R2 = ('m', frozenset({"f11", "f01"}))
IDENT_Q = {('m', frozenset({"f11", "f10"})): Q,
           ('m', frozenset({"f01", "f00"})): ('m', frozenset({"e01", "e00"}))}
COUPLE_Q = [(("e11", "e10"), ("f11", "f10"))]


def joint_hook(triple_a, triple_b):
    def hook(L, states):
        fib = [s for s in states
               if all(s[a] for a in triple_a) and all(s[b] for b in triple_b)]
        return {"joint_111_111": {
            "triples": [list(triple_a), list(triple_b)],
            "fiber_size": len(fib),
            "qr_values": sorted({(L.sval(s, Q), L.sval(s, R)) for s in fib}),
        }}
    return hook


def sharedq_hook(L, states):
    fib = [s for s in states if s["a1"] and s["a2"] and s["a3"]]
    coupling = all(s["e11"] + s["e10"] == s["f11"] + s["f10"] for s in states)
    return {
        "fiber_111_q_r1_r2_values": sorted(
            {(L.sval(s, Q), L.sval(s, R), L.sval(s, R2)) for s in fib}),
        "fiber_111_size": len(fib),
        "coupling_q_consistent_in_all_states": coupling,
    }



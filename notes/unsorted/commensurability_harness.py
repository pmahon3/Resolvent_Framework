def set_partitions(n):
    """All partitions of {0..n-1} with >= 2 cells, as tuples of frozensets."""
    def rec(elems):
        if not elems:
            yield []
            return
        first, rest = elems[0], elems[1:]
        for sub in rec(rest):
            for i in range(len(sub)):
                yield sub[:i] + [sub[i] | {first}] + sub[i + 1:]
            yield sub + [{first}]
    out = []
    for p in rec(list(range(n))):
        if len(p) >= 2:
            out.append(tuple(sorted((frozenset(c) for c in p),
                                    key=lambda s: sorted(s))))
    return sorted(out, key=lambda p: [sorted(c) for c in p])

def canon_key(partition):
    return tuple(tuple(sorted(c)) for c in partition)

def apply_perm(partition, perm):
    cells = [frozenset(perm[x] for x in c) for c in partition]
    return tuple(sorted(cells, key=lambda s: sorted(s)))

def canonical_protocols(n, k):
    """Lex-minimal representatives of S_n-orbits of k-subsets of partitions."""
    parts = set_partitions(n)
    pid = {canon_key(p): i for i, p in enumerate(parts)}
    perms = list(permutations(range(n)))
    # precompute permutation action on partition ids
    action = []
    for perm in perms:
        action.append([pid[canon_key(apply_perm(p, perm))] for p in parts])
    out = []
    for combo in combinations(range(len(parts)), k):
        key = combo  # sorted tuple of ids
        minimal = True
        for act in action:
            mapped = tuple(sorted(act[i] for i in combo))
            if mapped < key:
                minimal = False
                break
        if minimal:
            out.append([parts[i] for i in combo])
    return out

def build_protocol(n, contexts):
    """Cells, equality system (E, f), R-vertices, uniform point."""
    cells = []          # list of frozensets
    ctx_of = []         # context index per cell
    for ci, p in enumerate(contexts):
        for c in p:
            cells.append(c)
            ctx_of.append(ci)
    d = len(cells)
    E, f = [], []
    # per-context normalization
    for ci in range(len(contexts)):
        row = [Fraction(1) if ctx_of[j] == ci else Fraction(0) for j in range(d)]
        E.append(row)
        f.append(Fraction(1))
    # pairwise block-mass equalities (blocks = components of cell-intersection graph)
    for a, b in combinations(range(len(contexts)), 2):
        ia = [j for j in range(d) if ctx_of[j] == a]
        ib = [j for j in range(d) if ctx_of[j] == b]
        # union-find over ia+ib by nonempty intersection
        parent = {j: j for j in ia + ib}
        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x
        for j1 in ia:
            for j2 in ib:
                if cells[j1] & cells[j2]:
                    r1, r2 = find(j1), find(j2)
                    if r1 != r2:
                        parent[r1] = r2
        blocks = {}
        for j in ia + ib:
            blocks.setdefault(find(j), []).append(j)
        for blk in blocks.values():
            row = [Fraction(0)] * d
            for j in blk:
                row[j] = Fraction(1) if ctx_of[j] == a else Fraction(-1)
            if any(x != 0 for x in row):
                E.append(row)
                f.append(Fraction(0))
    # R vertices
    verts = []
    for w in range(n):
        verts.append([Fraction(1) if w in cells[j] else Fraction(0)
                      for j in range(d)])
    return cells, ctx_of, E, f, verts


# ----------------------------------------------------------------------
# Exact simplex (maximize c.x st A_eq x = b_eq, A_ub x <= b_ub, x >= 0)
# ----------------------------------------------------------------------

def simplex_max(c, A_eq, b_eq, A_ub, b_ub):
    """Exact rational simplex (Bland). Maximize c.x st A_eq x = b_eq,
    A_ub x <= b_ub, x >= 0. Returns (status, value, x)."""
    F = Fraction
    n = len(c)
    nub = len(A_ub)
    rows, rhs = [], []
    for a, b in zip(A_eq, b_eq):
        rows.append([F(x) for x in a] + [F(0)] * nub)
        rhs.append(F(b))
    for i, (a, b) in enumerate(zip(A_ub, b_ub)):
        r = [F(x) for x in a] + [F(0)] * nub
        r[n + i] = F(1)
        rows.append(r)
        rhs.append(F(b))
    nv = n + nub
    m = len(rows)
    for i in range(m):
        if rhs[i] < 0:
            rows[i] = [-x for x in rows[i]]
            rhs[i] = -rhs[i]
    ncols = nv + m
    T = [rows[i] + [F(1) if j == i else F(0) for j in range(m)] + [rhs[i]]
         for i in range(m)]
    basis = [nv + i for i in range(m)]

    def pivot(r, col, obj):
        p = T[r][col]
        T[r] = [x / p for x in T[r]]
        for i in range(m):
            if i != r and T[i][col] != 0:
                f0 = T[i][col]
                T[i] = [a - f0 * b for a, b in zip(T[i], T[r])]
        if obj is not None and obj[col] != 0:
            f0 = obj[col]
            for j in range(ncols + 1):
                obj[j] -= f0 * T[r][j]
        basis[r] = col

    def optimize(obj, allowed_cols):
        while True:
            col = -1
            for j in range(allowed_cols):
                if obj[j] > 0:
                    col = j
                    break
            if col == -1:
                return True
            r, best = -1, None
            for i in range(m):
                if T[i][col] > 0:
                    ratio = T[i][-1] / T[i][col]
                    if best is None or ratio < best or \
                       (ratio == best and basis[i] < basis[r]):
                        best, r = ratio, i
            if r == -1:
                return False
            pivot(r, col, obj)

    # Phase 1: minimize sum of artificials (maximize its negative).
    obj1 = [F(0)] * (ncols + 1)
    for i in range(m):
        for j in range(ncols + 1):
            obj1[j] += T[i][j]
    for j in range(nv, ncols):
        obj1[j] = F(0)
    optimize(obj1, nv)          # phase 1 is bounded; unbounded impossible
    if obj1[-1] != 0:
        return ('infeasible', None, None)
    # drive remaining artificials out where possible
    for i in range(m):
        if basis[i] >= nv:
            col = next((j for j in range(nv) if T[i][j] != 0), None)
            if col is not None:
                pivot(i, col, obj1)
    # Phase 2
    cvec = [F(x) for x in c] + [F(0)] * nub + [F(0)] * m
    obj2 = list(cvec) + [F(0)]
    for i in range(m):
        b = basis[i]
        if b < ncols and obj2[b] != 0:
            f0 = obj2[b]
            for j in range(ncols + 1):
                obj2[j] -= f0 * T[i][j]
    if not optimize(obj2, nv):
        return ('unbounded', None, None)
    x = [F(0)] * ncols
    for i in range(m):
        if basis[i] < ncols:
            x[basis[i]] = T[i][-1]
    val = sum(cv * xv for cv, xv in zip(cvec[:nv], x[:nv]))
    return ('optimal', val, x[:n])


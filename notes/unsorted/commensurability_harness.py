def analyze(n, k, contexts):
    cells, ctx_of, E, f, verts = build_protocol(n, contexts)
    d = len(cells)
    # rowspace of [E | f]
    aug = [row + [rhs] for row, rhs in zip(E, f)]
    Rr, Rp = rref(aug)
    hull_eqs, facets = r_hull_and_facets(verts)

    def max_over(c_obj, extra_ub):
        st, val, x = simplex_max(c_obj, E, f,
                                 [a for a, _ in extra_ub], [b for _, b in extra_ub])
        assert st == 'optimal', st
        return val, x

    # ---- separation test: C vs R ----
    sep_witness, sep_facet = None, None
    for u, rhs in hull_eqs:
        if in_rowspace(Rr, Rp, list(u) + [rhs]):
            continue        # C's own equalities force this hull equation
        val, x = max_over(list(u), [])
        if val != rhs:
            sep_witness, sep_facet = x, ('hull', u, rhs)
            break
        val2, x2 = max_over([-ui for ui in u], [])
        if -val2 != rhs:
            sep_witness, sep_facet = x2, ('hull', u, rhs)
            break
    if sep_witness is None:
        for a, b in facets:
            val, x = max_over(a, [])
            if val > b:
                sep_witness, sep_facet = x, ('facet', a, b)
                break
    if sep_witness is None:
        return {'verdict': 'R_EQUALS_C'}

    # ---- families ----
    F1 = family_I(n, cells, ctx_of, k)
    F2c, F2h = family_II(n, cells, ctx_of)
    F2 = F2c + F2h

    def subset_R(extra):
        """Is C cut by `extra` inside R? Returns (True, None) or (False, witness, facet)."""
        for u, rhs in hull_eqs:
            val, x = max_over(u, extra)
            if val > rhs:
                return False, x, ('hull+', u, rhs)
            val2, x2 = max_over([-ui for ui in u], extra)
            if -val2 < rhs:
                return False, x2, ('hull-', u, rhs)
        for a, b in facets:
            val, x = max_over(a, extra)
            if val > b:
                return False, x, ('facet', a, b)
        return True, None, None

    # Family 0 = R's affine-hull equations (integer pointwise syzygies),
    # imposable as inequality pairs.
    F0 = []
    for u, rhs in hull_eqs:
        F0.append((list(u), rhs))
        F0.append(([-t for t in u], -rhs))

    ok1, w1, fc1 = subset_R(F1)
    if ok1:
        verdict = 'FAMILY_I_COMPLETE'
        else_witness = None
    else:
        okc, wc, fcc = subset_R(F1 + F2c)
        if okc:
            verdict = 'NEED_CLIQUES_COMPLETE'
            else_witness = None
            ok12 = True
        else:
            ok12, w12, fc12 = subset_R(F1 + F2)
        if okc:
            pass
        elif ok12:
            verdict = 'NEED_ODDHOLES_COMPLETE'
            else_witness = None
        else:
            ok012, w012, fc012 = subset_R(F0 + F1 + F2)
            if ok012:
                verdict = 'NEED_SYZYGY_COMPLETE'
                else_witness = (w12, fc12)   # the syzygy-violating witness
            else:
                verdict = 'ELSE'
                else_witness = (w012, fc012)

    # ---- cone-membership of the separating R-facet (exotic vs in-cone) ----
    cone_flag = None
    if sep_facet is not None and sep_facet[0] == 'facet':
        a, b = sep_facet[1], sep_facet[2]
        fams = F1 + F2
        nf, ne = len(fams), len(Rr)
        # a = sum l_i fam_a_i + sum m_j Erow_j - nu ; b >= sum l_i fam_b_i + sum m_j f_j
        # variables: l >= 0 (nf), m free = mp - mn (2*ne), nu >= 0 (d), s >= 0 slack for b
        nv = nf + 2 * ne + d + 1
        Aeq, beq = [], []
        Erows = [row[:-1] for row in Rr]
        frhs = [row[-1] for row in Rr]
        for j in range(d):
            row = [Fraction(0)] * nv
            for i2, (fa, fb) in enumerate(fams):
                row[i2] = fa[j]
            for j2 in range(ne):
                row[nf + j2] = Erows[j2][j]
                row[nf + ne + j2] = -Erows[j2][j]
            row[nf + 2 * ne + j] = Fraction(-1)
            Aeq.append(row)
            beq.append(a[j])
        row = [Fraction(0)] * nv
        for i2, (fa, fb) in enumerate(fams):
            row[i2] = fb
        for j2 in range(ne):
            row[nf + j2] = frhs[j2]
            row[nf + ne + j2] = -frhs[j2]
        row[nf + 2 * ne + d] = Fraction(1)   # slack: sum + s = b  => sum <= b
        Aeq.append(row)
        beq.append(b)
        st, _, _ = simplex_max([Fraction(0)] * nv, Aeq, beq, [], [])
        cone_flag = 'in-cone' if st == 'optimal' else 'exotic'

    return {'verdict': verdict,
            'n': n, 'k': k,
            'contexts': [[sorted(c) for c in p] for p in contexts],
            'n_family_I': len(F1), 'n_family_II': len(F2),
            'sep_facet_cone': cone_flag,
            'else_witness': (None if else_witness is None else
                             [str(x) for x in else_witness[0]])}

# ----------------------------------------------------------------------

def main():
    n = int(sys.argv[1])
    ks = [int(sys.argv[2])] if len(sys.argv) > 2 else [2, 3]
    for k in ks:
        prots = canonical_protocols(n, k)
        tally = {}
        interesting = []
        out = open(f"commensurability_atlas_n{n}k{k}.jsonl", "w")
        for contexts in prots:
            res = analyze(n, k, contexts)
            v = res['verdict']
            tally[v] = tally.get(v, 0) + 1
            if v != 'R_EQUALS_C':
                out.write(json.dumps(res) + "\n")
                if v != 'FAMILY_I_COMPLETE':
                    interesting.append(res)
        out.close()
        print(f"n={n} k={k}: {len(prots)} canonical protocols; tally: {tally}")
        for r in interesting:
            print(f"  {r['verdict']}: contexts={r['contexts']}"
                  f" (|FI|={r['n_family_I']}, |FII|={r['n_family_II']},"
                  f" cone={r['sep_facet_cone']})")

if __name__ == '__main__':
    main()

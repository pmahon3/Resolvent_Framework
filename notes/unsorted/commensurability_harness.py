def rref(mat):
    """Reduced row echelon form; returns (rref_rows, pivot_cols)."""
    M = [list(map(Fraction, row)) for row in mat]
    rows, cols = len(M), (len(M[0]) if M else 0)
    piv_cols, r = [], 0
    for c in range(cols):
        pr = next((i for i in range(r, rows) if M[i][c] != 0), None)
        if pr is None:
            continue
        M[r], M[pr] = M[pr], M[r]
        M[r] = [x / M[r][c] for x in M[r]]
        for i in range(rows):
            if i != r and M[i][c] != 0:
                f = M[i][c]
                M[i] = [a - f * b for a, b in zip(M[i], M[r])]
        piv_cols.append(c)
        r += 1
        if r == rows:
            break
    return M[:r], piv_cols

def in_rowspace(rref_rows, piv_cols, vec):
    """Is vec in the rowspace given by an rref basis (augmented consistent)?"""
    v = list(map(Fraction, vec))
    for row, pc in zip(rref_rows, piv_cols):
        if v[pc] != 0:
            f = v[pc]
            v = [a - f * b for a, b in zip(v, row)]
    return all(x == 0 for x in v)


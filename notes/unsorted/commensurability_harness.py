def family_I(n, cells, ctx_of, k):
    """Elementary chains, pointwise-valid on N.
    Inequality: sum q(c_t) - q(T) <= m-1 (T=None: sum <= m-1)."""
    d = len(cells)
    ineqs = set()
    by_ctx = {}
    for j in range(d):
        by_ctx.setdefault(ctx_of[j], []).append(j)
    ctxs = sorted(by_ctx)
    for m in range(1, k + 1):
        for chosen_ctxs in combinations(ctxs, m):
            for combo in product(*[by_ctx[c] for c in chosen_ctxs]):
                rest = [j for j in range(d) if ctx_of[j] not in chosen_ctxs]
                for T in [None] + rest:
                    ok = True
                    for w in range(n):
                        lhs = sum(1 for j in combo if w in cells[j])
                        rhs = (m - 1) + (1 if (T is not None and w in cells[T]) else 0)
                        if lhs > rhs:
                            ok = False
                            break
                    if ok:
                        a = [Fraction(0)] * d
                        for j in combo:
                            a[j] += 1
                        if T is not None:
                            a[T] -= 1
                        ineqs.add((tuple(a), Fraction(m - 1)))
    return [(list(a), b) for a, b in ineqs]

def family_II(n, cells, ctx_of):
    """Clique + odd-hole inequalities of the cell-disjointness graph."""
    d = len(cells)
    adj = [[bool(i != j and not (cells[i] & cells[j])) for j in range(d)]
           for i in range(d)]
    ineqs = set()
    # maximal cliques (Bron-Kerbosch)
    cliques = []
    def bk(R, P, X):
        if not P and not X:
            cliques.append(R)
            return
        for v in list(P):
            bk(R | {v}, {u for u in P if adj[v][u]}, {u for u in X if adj[v][u]})
            P = P - {v}
            X = X | {v}
    bk(set(), set(range(d)), set())
    for Q in cliques:
        if len(Q) >= 2:
            a = [Fraction(1) if j in Q else Fraction(0) for j in range(d)]
            ineqs.add((tuple(a), Fraction(1)))
    # odd holes: chordless induced cycles of odd length >= 5
    cliq = [(list(a), b) for a, b in ineqs]
    holes = set()
    for L in range(5, d + 1, 2):
        for S in combinations(range(d), L):
            deg = [sum(1 for j in S if adj[i][j]) for i in S]
            if any(dg != 2 for dg in deg):
                continue
            # connected 2-regular = single cycle
            seen = {S[0]}
            frontier = [S[0]]
            while frontier:
                v = frontier.pop()
                for u in S:
                    if adj[v][u] and u not in seen:
                        seen.add(u)
                        frontier.append(u)
            if len(seen) == L:
                a = [Fraction(1) if j in S else Fraction(0) for j in range(d)]
                holes.add((tuple(a), Fraction((L - 1) // 2)))
    return cliq, [(list(a), b) for a, b in holes]

# ----------------------------------------------------------------------
# R geometry: affine hull equations + facets (exact)
# ----------------------------------------------------------------------

def r_hull_and_facets(verts):
    """Returns (hull_eqs, facets): hull_eqs = list of (u, u.v0) with u
    orthogonal to the hull directions; facets = list of (a, b) ambient lifts,
    valid a.v <= b on all verts with equality on a facet."""
    d = len(verts[0])
    v0 = verts[0]
    diffs = [[v[j] - v0[j] for j in range(d)] for v in verts[1:]]
    B, pivots = rref(diffs) if diffs else ([], [])
    r = len(B)  # dim of R
    # hull equations: null space of span(diffs): vectors u with u.diff = 0.
    # compute basis of orthogonal complement via rref of B as rows -> free vars
    hull_eqs = []
    piv = set(pivots)
    for free in range(d):
        if free in piv:
            continue
        u = [Fraction(0)] * d
        u[free] = Fraction(1)
        for row, pc in zip(B, pivots):
            u[pc] = -row[free]
        rhs = sum(u[j] * v0[j] for j in range(d))
        hull_eqs.append((u, rhs))
    # coordinates of vertices in hull basis: y_i solves via pivot columns of B
    coords = []
    for v in verts:
        w = [v[j] - v0[j] for j in range(d)]
        y = [Fraction(0)] * r
        # since B is rref of diffs (row space), solve w = y . B  (w in rowspace)
        ww = list(w)
        for i, pc in enumerate(pivots):
            y[i] = ww[pc]
            if y[i] != 0:
                ww = [a - y[i] * b for a, b in zip(ww, B[i])]
        coords.append(y)
    # facets of conv(coords) in R^r by brute force over vertex subsets
    facets = []
    if r == 0:
        return hull_eqs, facets
    seen = set()
    for S in combinations(range(len(coords)), r):
        pts = [coords[i] for i in S]
        # hyperplane through pts: solve for (g, h): g.p = h; fix scale via rref
        M = [pts[i] + [Fraction(1)] for i in range(r)]  # g.p - h = 0 -> [p,1].[g,-h]=0
        R2, piv2 = rref(M)
        if len(R2) < r:
            continue  # affinely dependent
        # null vector of M (r x (r+1)): one free var
        pivset = set(piv2)
        free = next(c for c in range(r + 1) if c not in pivset)
        gh = [Fraction(0)] * (r + 1)
        gh[free] = Fraction(1)
        for row, pc in zip(R2, piv2):
            gh[pc] = -row[free]
        g, h = gh[:r], -gh[r]
        vals = [sum(gi * yi for gi, yi in zip(g, y)) for y in coords]
        for sgn in (1, -1):
            gg = [sgn * x for x in g]
            hh = sgn * h
            vv = [sgn * x for x in vals]
            # supporting from this side: all vertices weakly below, some strictly
            if max(vv) == hh and any(x < hh for x in vv):
                # lift to ambient: a.q = g . y(q), y_i(q) recovered via pivots:
                # y_i = (q - v0)[pivot col path]; from coords computation:
                # y_i = (q - v0)[pivots[i]] adjusted by earlier rows -> build map
                a_amb = [Fraction(0)] * d
                # y as affine functions: replicate the coords loop symbolically
                # w = q - v0 ; iterate: y_i = w[pc_i]; w -= y_i * B[i]
                # => y_i = linear in q. Build incrementally with matrices.
                W = [[Fraction(1) if jj == ii else Fraction(0) for jj in range(d)]
                     for ii in range(d)]  # rows: w_j as functions of q (minus v0 handled via const)
                consts = [-v0[ii] for ii in range(d)]
                ycoef = []
                yconst = []
                for i2, pc in enumerate(pivots):
                    yc = list(W[pc])
                    y0c = consts[pc]
                    ycoef.append(yc)
                    yconst.append(y0c)
                    for jj in range(d):
                        if B[i2][jj] != 0:
                            W[jj] = [wa - B[i2][jj] * ya for wa, ya in zip(W[jj], yc)]
                            consts[jj] -= B[i2][jj] * y0c
                bb = hh
                for gi, yc, y0c in zip(gg, ycoef, yconst):
                    for jj in range(d):
                        a_amb[jj] += gi * yc[jj]
                    bb -= gi * y0c
                key = (tuple(a_amb), bb)
                if key not in seen:
                    seen.add(key)
                    facets.append((a_amb, bb))
    return hull_eqs, facets

